// Enhanced Health Check (DB Connected?)
app.get('/health', async (req, res) => {
  try {
    await mainDb.query('SELECT 1');
    // Note: vectorDb query check might block if the pool is exhausted or strict connectivity is required
    // For now, we check mainDb as critical path.
    res.json({
      status: 'healthy',
      checks: { database: 'connected' },
      uptime: process.uptime(),
      timestamp: new Date().toISOString()
    });
  } catch (e) {
    console.error('Health Check Failed:', e);
    res.status(503).json({ status: 'unhealthy', error: e.message });
  }
});

app.get('/api/health', (req, res) => {
  res.status(200).json({ status: 'ok', uptime: process.uptime(), timestamp: new Date().toISOString() });
});

// Routes
app.use('/api/auth', authRoutes);
app.use('/api/chat', chatRoutes);

// Catch-all (Production)
if (process.env.NODE_ENV === 'production') {
  app.get(/.*/, (req, res) => {
    res.sendFile(path.join(distPath, 'index.html'));
  });
}

// Database Initialization with Retry Logic
const initDB = async (retries = 5, delay = 5000) => {
  for (let i = 0; i < retries; i++) {
    try {
      console.log(`[DB] Attempting to connect... (Attempt ${i + 1}/${retries})`);
      await mainDb.query('SELECT 1');
      console.log('✅ Main DB Connected');

      await vectorDb.query('CREATE EXTENSION IF NOT EXISTS vector');
      console.log('✅ Vector DB Connected & Extension Verified');
      return true; // Success!
    } catch (e) {
      console.error(`❌ DB Connection Attempt ${i + 1} failed:`, e.message);
      if (i < retries - 1) {
        console.log(`[DB] Retrying in ${delay / 1000}s...`);
        await new Promise(res => setTimeout(res, delay));
      }
    }
  }
  console.error('🛑 Critical: Could not connect to Database after multiple attempts.');
  return false;
};

// Start Server & Handle Shutdown
const server = app.listen(PORT, async () => {
  await initDB();
  console.log(`🚀 Server running on port ${PORT}`);
});

server.on('error', (e) => {
  if (e.code === 'EADDRINUSE') {
    console.error(`❌ ERROR: Port ${PORT} is already in use.`);
  } else {
    console.error('❌ Server error:', e);
  }
});

// Graceful Shutdown
const attemptShutdown = async (signal) => {
  console.log(`\n🛑 ${signal} received. Starting graceful shutdown...`);

  server.close(async () => {
    console.log('HTTP server closed.');
    try {
      await mainDb.end();
      await vectorDb.end();
      console.log('Database connections closed.');
      process.exit(0);
    } catch (err) {
      console.error('Error during database disconnect:', err);
      process.exit(1);
    }
  });

  // Force exit if hanging
  setTimeout(() => {
    console.error('Force shutdown after timeout.');
    process.exit(1);
  }, 10000); // 10s
};

process.on('SIGTERM', () => attemptShutdown('SIGTERM'));
process.on('SIGINT', () => attemptShutdown('SIGINT'));
